import {readFile,writeFile} from 'node:fs/promises';
const characterAssets={};
for(const name of ['jemissi-pen-v1.png','jemissi-face-v1.png','jemissi-thinking-v1.png','jemissi-icon-v1.png']){
 characterAssets['/character/'+name]={type:'image/png',base64:(await readFile(new URL('../public/character/'+name,import.meta.url))).toString('base64')};
}
characterAssets['/favicon.svg']={type:'image/svg+xml',base64:(await readFile(new URL('../public/favicon.svg',import.meta.url))).toString('base64')};
const css=await readFile(new URL('../public/design/site-20261110-motion.css',import.meta.url),'utf8');
const js=await readFile(new URL('../public/design/site-20261110-motion.js',import.meta.url),'utf8');
const code='// Generated by scripts/build-design-module.mjs; edit public/design and public/character sources.\n'+Object.entries({css,js,characterAssets}).map(([name,value])=>'export const '+name+'='+JSON.stringify(value)+';\n').join('');
await writeFile(new URL('../src/generated/site-design.mjs',import.meta.url),code);
